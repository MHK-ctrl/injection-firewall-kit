"""Render benchmark results as Markdown (and keep the JSON shape stable)."""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

CATEGORY_LABELS = {
    "direct_instruction_override": "Direct instruction override",
    "role_hijack": "Role / system-message spoofing",
    "delimiter_spoof": "Delimiter & chat-template spoofing",
    "hidden_text": "Hidden text",
    "encoding_obfuscation": "Encoding / obfuscation",
    "multilingual_injection": "Multilingual injection",
    "payload_splitting": "Payload splitting",
    "fake_tool_result": "Fake tool results",
    "exfiltration": "Exfiltration via links / beacons",
    "tool_abuse": "Tool-abuse requests",
    "social_engineering": "Social engineering / authority",
    "context_poisoning": "Context poisoning",
}

CARRIER_LABELS = {
    "email_body": "Email body",
    "html_page": "HTML page",
    "markdown_doc": "Markdown document",
    "pdf_text": "PDF-extracted text",
    "json_tool_output": "JSON tool output",
    "code_comment": "Code comment",
    "csv_cell": "CSV cell",
    "calendar_invite": "Calendar invite",
    "filename_metadata": "Filename / metadata",
}


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _table(rows: Iterable[dict[str, float]], names: dict[str, str]) -> str:
    lines = [
        "| Group | Attacks | Benign | Recall | Precision | F1 | False-positive rate |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for key, metrics in rows:
        label = names.get(key, key)
        lines.append(
            f"| {label} | {metrics['attacks']} | {metrics['benign']} | "
            f"{_pct(metrics['recall'])} | {_pct(metrics['precision'])} | "
            f"{_pct(metrics['f1'])} | {_pct(metrics['false_positive_rate'])} |"
        )
    return "\n".join(lines)


def render_markdown(results: dict) -> str:
    overall = results["overall"]
    totals = results["totals"]
    scores = results["score_distribution"]

    parts: list[str] = []
    parts.append("# Benchmark results\n")
    parts.append(
        f"Generated by `ifk bench` on {results['generated_at']} against "
        f"**{totals['samples']} samples** ({totals['attacks']} attacks, "
        f"{totals['benign']} benign look-alikes).\n"
    )
    parts.append(
        f"Policy: `{results['policy']}`. A sample counts as *flagged* when its risk score "
        f"is at or above **{results['threshold']}** (the warn threshold).\n"
    )

    parts.append("## Headline numbers\n")
    parts.append("| Metric | Value |")
    parts.append("| --- | ---: |")
    parts.append(f"| Recall (attacks caught) | {_pct(overall['recall'])} |")
    parts.append(f"| Precision | {_pct(overall['precision'])} |")
    parts.append(f"| F1 | {_pct(overall['f1'])} |")
    parts.append(f"| False-positive rate (benign flagged) | {_pct(overall['false_positive_rate'])} |")
    parts.append(f"| Accuracy | {_pct(overall['accuracy'])} |")
    parts.append(
        f"| True positives / false negatives | {overall['tp']} / {overall['fn']} |"
    )
    parts.append(f"| False positives / true negatives | {overall['fp']} / {overall['tn']} |")
    parts.append("")

    parts.append("## Score distribution\n")
    parts.append("| Group | Min | Median | Mean | Max |")
    parts.append("| --- | ---: | ---: | ---: | ---: |")
    for label, key in (("Attacks", "attacks"), ("Benign", "benign")):
        dist = scores[key]
        parts.append(
            f"| {label} | {dist['min']} | {dist['median']} | {dist['mean']} | {dist['max']} |"
        )
    parts.append("")

    parts.append("## Per category\n")
    parts.append(_table(sorted(results["per_category"].items()), CATEGORY_LABELS))
    parts.append("")

    parts.append("## Per carrier\n")
    parts.append(_table(sorted(results["per_carrier"].items()), CARRIER_LABELS))
    parts.append("")

    parts.append("## Detector activity\n")
    parts.append("How often each detector produced at least one finding:\n")
    parts.append("| Detector | Samples with a finding |")
    parts.append("| --- | ---: |")
    for name, count in results["detector_hits"].items():
        parts.append(f"| `{name}` | {count} |")
    parts.append("")

    parts.append("## Policy actions\n")
    parts.append("| Action | Samples |")
    parts.append("| --- | ---: |")
    for action, count in results["actions"].items():
        parts.append(f"| {action} | {count} |")
    parts.append("")

    misses = results["false_negatives"]
    parts.append("## Missed attacks\n")
    if misses:
        parts.append("| ID | Category | Carrier | Score | Severity |")
        parts.append("| --- | --- | --- | ---: | --- |")
        for miss in misses:
            parts.append(
                f"| {miss['id']} | {miss['category']} | {miss['carrier']} | "
                f"{miss['score']} | {miss['severity']} |"
            )
    else:
        parts.append("None: every attack sample was flagged at this threshold.")
    parts.append("")

    fps = results["false_positives"]
    parts.append("## Benign samples that were flagged\n")
    if fps:
        parts.append(
            f"{len(fps)} of {totals['benign']} benign samples were flagged. Each one is a "
            "real cost: a legitimate email or document that a UI would mark as hostile.\n"
        )
        parts.append("| ID | Resembles | Carrier | Score | Action | Detectors |")
        parts.append("| --- | --- | --- | ---: | --- | --- |")
        for fp in fps:
            parts.append(
                f"| {fp['id']} | {fp['category']} | {fp['carrier']} | {fp['score']} | "
                f"{fp['action']} | {', '.join(fp['detectors']) or '-'} |"
            )
    else:
        parts.append("None.")
    parts.append("")

    parts.append("## Read this before quoting the numbers\n")
    parts.append(
        "The corpus is small, synthetic and written by the same people who wrote the "
        "detectors. High recall here means the rules cover **these** phrasings; it says "
        "nothing about a semantically paraphrased attack in a language the corpus does not "
        "cover. Treat this as a regression test, not as a security rating. See "
        "`docs/06-limitations-and-honesty.md`.\n"
    )
    return "\n".join(parts)


def write_reports(results: dict, markdown_path: str | Path, json_path: str | Path | None = None) -> None:
    Path(markdown_path).write_text(render_markdown(results), encoding="utf-8")
    if json_path:
        Path(json_path).write_text(json.dumps(results, indent=2), encoding="utf-8")


__all__ = ["CARRIER_LABELS", "CATEGORY_LABELS", "render_markdown", "write_reports"]
